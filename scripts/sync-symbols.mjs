// Commit font assets and repertoire so app builds never depend on a sibling checkout.
import { createHash } from 'node:crypto';
import { execFileSync } from 'node:child_process';
import { copyFileSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const source = process.env.DAOUI_PATH ?? resolve(root, '../daoUI');
const receipt = resolve(root, 'src/theme/symbols.provenance.json');
const hash = (file) => createHash('sha256').update(readFileSync(file)).digest('hex');
if (process.argv.includes('--check')) {
  const { files } = JSON.parse(readFileSync(receipt, 'utf8'));
  for (const [file, expected] of Object.entries(files))
    if (hash(resolve(root, file)) !== expected) throw new Error(`Symbol asset drift: ${file}; rebuild with sync-symbols`);
  console.log('Symbol assets, repertoire and editor build match provenance');
} else {
  const inputs = ['fonts/kairos-astrology/proof/ZojerSymbols-Regular.ttf', 'fonts/kairos-astrology/manifest.json', 'fonts/elder-futhark/repertoire.json'];
  const manifest = JSON.parse(readFileSync(resolve(source, inputs[1]), 'utf8'));
  const runes = JSON.parse(readFileSync(resolve(source, inputs[2]), 'utf8'));
  const rows = manifest.symbols.map((r) => ({
    id: r.id === 'eros-asteroid' ? 'heart' : r.id,
    name: r.id === 'eros-asteroid' ? 'Heart' : r.name,
    glyph: r.character + (r.text_variation ? '\uFE0E' : ''),
    category: r.category,
  }));
  for (const r of runes) {
    rows.push({ id: r.name.toLowerCase(), name: r.name, glyph: (r.preferred_variant ?? r).character, category: 'rune' });
    if (r.preferred_variant) rows.push({ id: 'ingwaz-diamond', name: 'Ingwaz (diamond)', glyph: r.character, category: 'rune' });
  }
  mkdirSync(resolve(root, 'assets/fonts'), { recursive: true });
  copyFileSync(resolve(source, inputs[0]), resolve(root, 'assets/fonts/ZojerSymbols-Regular.ttf'));
  writeFileSync(resolve(root, 'src/lib/symbols.gen.ts'), '// Generated by scripts/sync-symbols.mjs; edit the daoUI sources.\nexport const symbols = '+JSON.stringify(rows, null, 2)+' as const;\n');
  execFileSync(process.env.SYMBOL_FONT_PYTHON ?? 'python3', [resolve(root, 'scripts/build-editor-font.py')], { stdio: 'inherit' });
  const names = ['assets/fonts/ZojerSymbols-Regular.ttf', 'assets/fonts/JeraEditor-Regular.otf', 'assets/fonts/ABCWhyteEdu-Book.otf', 'src/lib/symbols.gen.ts', 'scripts/build-editor-font.py', 'scripts/requirements-fonts.txt'];
  const commit = execFileSync('git', ['-C', source, 'rev-parse', 'HEAD'], { encoding: 'utf8' }).trim();
  const dirty = !!execFileSync('git', ['-C', source, 'status', '--porcelain', '--', ...inputs], { encoding: 'utf8' }).trim();
  writeFileSync(receipt, JSON.stringify({ source: 'daoUI', commit, dirty, inputs: Object.fromEntries(inputs.map((f) => [f, hash(resolve(source, f))])), files: Object.fromEntries(names.map((f) => [f, hash(resolve(root, f))])) }, null, 2)+'\n');
}
