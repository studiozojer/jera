// Generate-and-commit daoUI's layout, type and font assets for standalone EAS builds.
import { execFileSync } from 'node:child_process';
import { copyFileSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const source = process.env.DAOUI_PATH ?? resolve(root, '../daoUI');
const commit = execFileSync(
  'git',
  ['-C', source, 'rev-parse', '--short', 'HEAD'],
  { encoding: 'utf8' },
).trim();
const swift = readFileSync(
  resolve(source, 'Sources/DaoUI/DesignTokens.swift'),
  'utf8',
);
const groups = {};
for (const group of ['Spacing', 'Radius', 'Layout']) {
  const body = swift.match(
    new RegExp(`public enum ${group} \\{([\\s\\S]*?)\\n    \\}`),
  )?.[1];
  if (!body) throw new Error(`Missing daoUI ${group}`);
  groups[group.toLowerCase()] = Object.fromEntries(
    [...body.matchAll(/public static let (\w+): CGFloat = ([\d.]+)/g)].map(
      (m) => [m[1], Number(m[2])],
    ),
  );
}
const fonts = {
  body: 'ABCWhyteEdu-Book',
  display: 'ABCWhyteInktrap-Regular',
  mono: 'PPFraktionMono-Regular',
};
const canonicalType = JSON.parse(
  readFileSync(resolve(source, 'type.json'), 'utf8'),
).styles;
const typeScale = Object.fromEntries(
  Object.entries(canonicalType).map(([name, entry]) => [
    name,
    {
      fontFamily: entry.font,
      fontSize: entry.size,
      lineHeight: entry.lineHeight,
      ...(entry.trackingPercent
        ? { letterSpacing: (entry.size * entry.trackingPercent) / 100 }
        : {}),
    },
  ]),
);
mkdirSync(resolve(root, 'assets/fonts'), { recursive: true });
for (const face of Object.values(fonts))
  copyFileSync(
    resolve(source, `Sources/DaoUI/Fonts/${face}.otf`),
    resolve(root, `assets/fonts/${face}.otf`),
  );
writeFileSync(
  resolve(root, 'src/theme/foundation.gen.ts'),
  `// Generated by scripts/sync-foundation.mjs from daoUI @ ${commit}.\n// Layout: DesignTokens.swift; typography: type.json; fonts: Sources/DaoUI/Fonts.\n${Object.entries(
    groups,
  )
    .map(
      ([name, value]) =>
        `export const ${name} = ${JSON.stringify(value, null, 2)} as const;`,
    )
    .join(
      '\n',
    )}\nexport const typeScale = ${JSON.stringify(typeScale, null, 2)} as const;\nexport const fonts = ${JSON.stringify(fonts, null, 2)} as const;\nexport const fontMap = {\n${Object.values(
    fonts,
  )
    .map((face) => `  '${face}': require('../../assets/fonts/${face}.otf'),`)
    .join('\n')}\n};\n`,
);
console.log(`Synced daoUI foundation @ ${commit}`);
